def clone_or_get_repo(github_client: Github, repo_name: str, work_dir: str) -> None:
    """Clone repository to work directory.

    Args:
        github_client: GitHub API client
        repo_name: Repository name (owner/repo)
        work_dir: Directory to clone into
    """
    from git import Repo

    repo = github_client.get_repo(repo_name)
    clone_url = repo.clone_url

    # Clone with token for authentication
    clone_url_with_token = clone_url.replace(
        "https://", f"https://{Config.GITHUB_TOKEN}@"
    )

    if not os.path.exists(os.path.join(work_dir, ".git")):
        Repo.clone_from(clone_url_with_token, work_dir)
    else:
        # Already cloned, just pull latest
        local_repo = Repo(work_dir)
        local_repo.remote("origin").pull()


def process_github_issue(
    issue_number: int,
    branch_name: Optional[str] = None,
) -> Dict[str, Any]:
    """Process a GitHub issue end-to-end.

    Workflow:
    1. Get issue description (specification)
    2. Normalize and enhance specification
    3. Clone repository to work directory
    4. Run planning-UAT loop to generate code
    5. Commit and push to new branch
    6. Create pull request
    7. Check CI status
    8. Wait for/process user feedback if needed

    Args:
        issue_number: GitHub issue number to process
        branch_name: Optional custom branch name (auto-generated if not provided)

    Returns:
        Dict with workflow results
    """
    # Initialize GitHub client
    github_client = Github(Config.GITHUB_TOKEN)
    repo = github_client.get_repo(Config.GITHUB_REPO)
    issue = repo.get_issue(number=issue_number)

    print(f"\n{'='*70}")
    print(f"🔄 Processing GitHub Issue #{issue_number}")
    print(f"📋 Title: {issue.title}")
    print(f"{'='*70}\n")

    # Comment on issue that we're starting
    issue.create_comment(
        "🤖 **LilAgent is processing this issue**\n\n"
        "I'll generate code based on your requirements and create a pull request for review.\n\n"
        "Status: Starting specification processing..."
    )

    try:
        # Step 1: Get specification from issue
        spec_text = f"# {issue.title}\n\n{issue.body}"

        # Step 2: Normalize and enhance
        print("📝 Processing specification...")
        normalized_spec = normalize_spec(spec_text)
        enhanced_spec = enhance_spec(normalized_spec)

        issue.create_comment(
            "✅ **Specification processed**\n\n"
            "I've analyzed your requirements and created a structured specification.\n\n"
            "Status: Cloning repository and setting up workspace..."
        )

        # Step 3: Setup work directory
        work_dir = tempfile.mkdtemp(prefix="lilagent-github-")
        clone_or_get_repo(github_client, Config.GITHUB_REPO, work_dir)

        # Save enhanced spec
        spec_path = Path(work_dir) / "SPECIFICATION.md"
        with open(spec_path, 'w') as f:
            f.write(enhanced_spec)

        issue.create_comment(
            "✅ **Workspace ready**\n\n"
            f"Working in temporary directory: `{work_dir}`\n\n"
            "Status: Starting implementation with multi-agent system..."
        )

        # Step 4: Run implementation
        print("🚀 Running multi-agent implementation...")
        result = run_planning_uat_loop(
            work_dir=work_dir,
            specification=enhanced_spec,
        )

        if not result['success']:
            issue.create_comment(
                "⚠️ **Implementation completed with issues**\n\n"
                f"UAT did not pass after {result['iterations']} iterations.\n\n"
                "I'll create a draft PR with the current state for you to review."
            )

        # Step 5: Commit and push
        branch_name = branch_name or f"lilagent/issue-{issue_number}"
        print(f"📤 Pushing to branch: {branch_name}")

        from git import Repo
        local_repo = Repo(work_dir)

        # Create and checkout branch
        try:
            local_repo.git.checkout('-b', branch_name)
        except:
            local_repo.git.checkout(branch_name)

        # Add and commit
        local_repo.git.add(A=True)
        if local_repo.is_dirty() or local_repo.untracked_files:
            commit_message = f"Implement #{issue_number}: {issue.title}\n\nGenerated by LilAgent multi-agent system"
            local_repo.index.commit(commit_message)

            # Push
            local_repo.remote('origin').push(branch_name, set_upstream=True)

            issue.create_comment(
                "✅ **Code pushed to branch**\n\n"
                f"Branch: `{branch_name}`\n\n"
                "Status: Creating pull request..."
            )

        # Step 6: Create PR
        pr_body = f"""## 🤖 Auto-generated by LilAgent

This PR implements the requirements from issue #{issue_number}.

### Specification
The implementation is based on the enhanced specification saved in `SPECIFICATION.md`.

### Implementation Summary
- Planning iterations: {result['iterations']}
- UAT Status: {'✅ Passed' if result['uat_passed'] else '⚠️ Needs Review'}

### Next Steps
1. Review the generated code
2. Check that CI passes
3. Test the implementation locally if needed
4. Provide feedback via comments if changes are needed

### Testing
```bash
# Clone and test
git checkout {branch_name}
# Follow instructions in README.md
```

Closes #{issue_number}
"""

        pr = repo.create_pull(
            title=f"Implement: {issue.title}",
            body=pr_body,
            head=branch_name,
            base=Config.GITHUB_DEFAULT_BRANCH,
            draft=not result['uat_passed'],  # Draft if UAT failed
        )

        issue.create_comment(
            f"✅ **Pull Request created!**\n\n"
            f"🔗 PR #{pr.number}: {pr.html_url}\n\n"
            f"The PR is {'ready for review' if result['uat_passed'] else 'in draft mode - please review and provide feedback'}.\n\n"
            "I'll monitor the PR for:\n"
            "- ✅ CI/CD pipeline results\n"
            "- 💬 Your questions or feedback\n"
            "- 🔄 Change requests\n\n"
            "Feel free to comment on the PR with any questions or changes needed!"
        )

        print(f"\n✅ Pull Request created: {pr.html_url}\n")

        # Step 7: Monitor CI
        print("⏳ Checking CI status...")
        import time
        time.sleep(10)  # Wait for CI to start

        commit = repo.get_commit(pr.head.sha)
        ci_status = commit.get_combined_status()

        ci_comment = f"### 🔧 CI Status: {ci_status.state.upper()}\n\n"
        if ci_status.state == "success":
            ci_comment += "✅ All checks passed!"
        elif ci_status.state == "failure":
            ci_comment += "❌ Some checks failed:\n\n"
            for check in ci_status.statuses:
                if check.state == "failure":
                    ci_comment += f"- **{check.context}**: {check.description}\n"
            ci_comment += "\nI can help fix these issues if you provide guidance!"
        elif ci_status.state == "pending":
            ci_comment += "⏳ Checks are still running. I'll monitor and update."

        pr.create_issue_comment(ci_comment)

        return {
            "success": True,
            "issue_number": issue_number,
            "pr_number": pr.number,
            "pr_url": pr.html_url,
            "branch": branch_name,
            "work_dir": work_dir,
            "uat_passed": result['uat_passed'],
            "ci_status": ci_status.state,
        }

    except Exception as e:
        error_msg = (
            f"❌ **Error during processing**\n\n"
            f"```\n{str(e)}\n```\n\n"
            f"Please review the error and I can try again if needed."
        )
        issue.create_comment(error_msg)
        raise


def monitor_pr_for_feedback(pr_number: int, timeout_minutes: int = 60) -> Dict[str, Any]:
    """Monitor PR for user feedback and respond.

    Args:
        pr_number: Pull request number to monitor
        timeout_minutes: How long to monitor before stopping

    Returns:
        Dict with feedback processing results
    """
    github_client = Github(Config.GITHUB_TOKEN)
    repo = github_client.get_repo(Config.GITHUB_REPO)
    pr = repo.get_pull(number=pr_number)

    print(f"\n👀 Monitoring PR #{pr_number} for feedback...")
    print(f"Will check for {timeout_minutes} minutes\n")

    import time
    start_time = time.time()
    last_comment_count = pr.comments

    while (time.time() - start_time) < (timeout_minutes * 60):
        pr = repo.get_pull(number=pr_number)  # Refresh

        # Check for new comments
        current_comments = pr.comments
        if current_comments > last_comment_count:
            comments = list(pr.get_issue_comments())
            new_comments = comments[last_comment_count:]

            for comment in new_comments:
                if comment.user.login != github_client.get_user().login:  # Not our own comment
                    print(f"\n💬 New comment from {comment.user.login}:")
                    print(f"{comment.body}\n")

                    # Here you could add logic to parse feedback and trigger re-implementation
                    # For now, just acknowledge
                    pr.create_issue_comment(
                        f"👋 Thanks for the feedback, @{comment.user.login}! "
                        "I've noted your comment and can make changes if you provide specific instructions."
                    )

            last_comment_count = current_comments

        # Check CI status
        commit = repo.get_commit(pr.head.sha)
        ci_status = commit.get_combined_status()

        if ci_status.state == "failure":
            print("❌ CI failed - could trigger remediation here")

        time.sleep(30)  # Check every 30 seconds

    return {"monitored": True, "duration": time.time() - start_time}
